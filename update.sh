#!/usr/bin/env bash
#
# Короткий вход в обновление. Нужен по двум причинам.
#
# Первая — та же, что у install.sh: настоящий скрипт называется
# ОБНОВИТЬ-НА-СЕРВЕРЕ.sh, по-русски, чтобы владелец понимал, что запускает.
# Но набрать это имя в консоли сервера нельзя: там английская раскладка
# и никакой вставки.
#
# Вторая важнее. Этот файл всегда берёт свежий скрипт обновления с GitHub,
# а не тот, что уже лежит на сервере. Разница выясняется в неприятный момент:
# если в самом скрипте обновления что-то починили, старая копия на сервере
# об этой починке не знает — и чинить себя не умеет ровно потому, что сломана.
# Так и вышло однажды: обновление отказывалось идти из-за файла, который
# лечился только обновлением.
#
#   curl -sL https://raw.githubusercontent.com/djaha12/Asher/HEAD/update.sh | bash
#
# Можно передать папку системы и флаги настоящего скрипта:
#   … | bash -s -- /home/asher/app --force

set -euo pipefail

REPO=https://github.com/djaha12/Asher.git
WORK=/tmp/asher-обновление
APP_DIR=/home/asher/app
EXTRA=()

# Путь узнаём по ведущей косой черте, остальное считаем флагами настоящего
# скрипта и передаём ему как есть — чтобы этот файл не пришлось править
# каждый раз, когда там появится новый флаг.
for arg in "$@"; do
  case "$arg" in
    /*) APP_DIR="$arg" ;;
    *) EXTRA+=("$arg") ;;
  esac
done

[ "$(id -u)" = 0 ] || {
  printf '\n\033[31m%s\033[0m\n\n' "Запускать от root." >&2
  exit 1
}

command -v git >/dev/null || {
  export DEBIAN_FRONTEND=noninteractive
  apt-get -o DPkg::Lock::Timeout=300 update -qq
  apt-get -o DPkg::Lock::Timeout=300 install -y -qq git
}

# Повторный запуск не должен спотыкаться об остатки прошлого.
rm -rf "$WORK"
git clone --quiet --depth 1 "$REPO" "$WORK"

# ${EXTRA[@]+…} — без этой обёртки set -u роняет строку на пустом наборе
# флагов в bash до 4.4, а на сервере может стоять именно такой.
exec bash "$WORK/ОБНОВИТЬ-НА-СЕРВЕРЕ.sh" "$APP_DIR" ${EXTRA[@]+"${EXTRA[@]}"}
