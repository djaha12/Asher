'use strict';
require('./устройство');   // проверки называют себя устройством, как настоящее приложение
/*
 * Сверка кассы.
 *
 * Шесть продавцов принимают наличные, и сверить ящик с системой было нечем.
 * Здесь проверяется главное — АРИФМЕТИКА: что «должно быть в ящике» считается
 * правильно и что расхождение находится там, где оно есть на самом деле.
 *
 * Отдельно проверяется то, на чём такие вещи обычно и ломаются: оплата картой
 * в ящик не попадает, возврат из него уходит, а продажа не должна посчитаться
 * дважды из-за того, что она пишется и в платежи, и в финансовые операции.
 */
const BASE = process.env.BASE || 'http://127.0.0.1:3122';

let ok = 0, fail = 0;
const провалы = [];
const check = (имя, усл, доп) => {
  if (усл) { ok++; console.log('  ok  ' + имя); }
  else { fail++; провалы.push(имя); console.log('  FAIL ' + имя, доп === undefined ? '' : String(доп).slice(0, 220)); }
};
const около = (a, b) => Math.abs(Number(a) - Number(b)) < 0.011;

/*
 * Своей отметки устройства здесь нет намеренно: её подставляет тесты/устройство.js,
 * общую для всех наборов. Со своим ключом набор выглядел бы новым устройством —
 * и в общем прогоне, где админ уже вошёл с другого, попал бы на экран ожидания
 * вместо работы.
 */
function сеанс() {
  let cookie = '';
  return {
    async войти(логин, пароль) {
      const r = await fetch(BASE + '/api/login', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ username: логин, password: пароль }),
      });
      cookie = (r.headers.get('set-cookie') || '').split(';')[0];
      return r.status === 200;
    },
    async зов(метод, путь, тело) {
      const opts = { method: метод, headers: { Cookie: cookie } };
      if (тело !== undefined) {
        opts.headers['Content-Type'] = 'application/json';
        opts.body = JSON.stringify(тело);
      }
      const r = await fetch(BASE + путь, opts);
      let data = null;
      try { data = await r.json(); } catch { /* пусто */ }
      return { status: r.status, data };
    },
  };
}

async function main() {
  const админ = сеанс();
  if (!await админ.войти('admin', 'admin123')) { console.error('Не удалось войти'); process.exit(2); }

  console.log('=== 1. Первая сверка — только начало отсчёта ===');
  /*
   * Сравнивать первой сверке не с чем: система не знает, сколько денег лежало
   * в ящике до неё. Раньше здесь считалось «движение за всю историю», и на живой
   * базе это уходило в минус — продавец при первой же сверке видел бы
   * бессмысленную цифру и перестал бы ей верить.
   */
  const о0 = (await админ.зов('GET', '/api/cash/expected')).data;
  check('система говорит, что сверок ещё не было', о0['первая'] === true, о0['первая']);
  check('и ничего не выдумывает: движение нулевое',
    около(о0['движение']['итого'], 0), о0['движение']);

  const первая = (await админ.зов('POST', '/api/cash/count', { counted: 50000 })).data;
  check('первая сверка записана', первая['первая'] === true, первая);
  check('расхождения у неё нет', около(первая['разница'], 0), первая['разница']);
  check('названа началом отсчёта', первая['словами'] === 'начало отсчёта', первая['словами']);

  console.log('\n=== 2. Продажа наличными увеличивает ожидаемое ===');
  const склад = (await админ.зов('GET', '/api/cash/expected')).data;
  const былоОжидание = склад['ожидается'];

  const вналичии = ((await админ.зов('GET', '/api/products?status=in_stock&limit=10')).data.items || [])
    .filter(p => p.status === 'in_stock');
  check('есть что продать', вналичии.length >= 4, вналичии.length);

  const чек1 = await админ.зов('POST', '/api/sales', {
    items: [{ product_id: вналичии[0].id, discount: 0 }], payment_method: 'cash',
  });
  check('продажа наличными прошла', чек1.status === 200, чек1.data);
  const ценаНал = Number(вналичии[0].retail_price);

  const о1 = (await админ.зов('GET', '/api/cash/expected')).data;
  check('ожидаемое выросло ровно на сумму чека',
    около(о1['ожидается'], былоОжидание + ценаНал),
    `${о1['ожидается']} вместо ${былоОжидание + ценаНал}`);

  console.log('\n=== 3. Оплата картой в ящик НЕ попадает ===');
  /*
   * Самая частая ошибка в таких расчётах. Карта — это деньги магазина, но не
   * деньги в ящике: если посчитать их вместе, каждая безналичная продажа
   * превращалась бы в «недостачу» ровно на свою сумму.
   */
  const доКарты = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  const чекКартой = await админ.зов('POST', '/api/sales', {
    items: [{ product_id: вналичии[1].id, discount: 0 }], payment_method: 'card',
  });
  check('продажа картой прошла', чекКартой.status === 200, чекКартой.data);
  const послеКарты = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  check('ожидаемое в ящике не изменилось', около(послеКарты, доКарты),
    `${послеКарты} вместо ${доКарты}`);

  console.log('\n=== 4. Возврат уменьшает ожидаемое ===');
  const доВозврата = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  const детали = (await админ.зов('GET', `/api/sales/${чек1.data.id}`)).data;
  const позиция = (детали.items || [])[0];
  const возврат = await админ.зов('POST', `/api/sales/${чек1.data.id}/return`,
    { item_ids: [позиция.id] });
  check('возврат оформлен', возврат.status === 200, возврат.data);
  const послеВозврата = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  check('ожидаемое уменьшилось на сумму возврата',
    около(послеВозврата, доВозврата - ценаНал),
    `${послеВозврата} вместо ${доВозврата - ценаНал}`);

  console.log('\n=== 5. Расход из кассы тоже учитывается ===');
  const доРасхода = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  const расход = await админ.зов('POST', '/api/finance', {
    type: 'expense', category: 'Хозяйственные', amount: 1500, note: 'Вода в кулер', cash: true,
  });
  check('расход записан', расход.status === 200, расход.data);
  const послеРасхода = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  check('ожидаемое уменьшилось на 1500', около(послеРасхода, доРасхода - 1500),
    `${послеРасхода} вместо ${доРасхода - 1500}`);

  console.log('\n=== 5б. Расход ПЕРЕВОДОМ кассу не трогает ===');
  /*
   * Аренда и зарплата часто уходят переводом. Денег из ящика они не забирают,
   * и если считать их наличными, сверка каждый месяц показывала бы недостачу
   * ровно на сумму аренды — то есть врала бы.
   */
  const доПеревода = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  const переводом = await админ.зов('POST', '/api/finance', {
    type: 'expense', category: 'Аренда', amount: 90000, note: 'Аренда за месяц', cash: false,
  });
  check('безналичный расход записан', переводом.status === 200, переводом.data);
  const послеПеревода = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  check('ожидаемое в ящике не изменилось', около(послеПеревода, доПеревода),
    `${послеПеревода} вместо ${доПеревода}`);

  console.log('\n=== 6. Недостача видна и названа словами ===');
  const ждём = (await админ.зов('GET', '/api/cash/expected')).data['ожидается'];
  const ответ = await админ.зов('POST', '/api/cash/count',
    { counted: ждём - 300, note: 'проверка недостачи' });
  const недостача = ответ.data || {};
  check('расхождение посчитано верно', около(недостача['разница'], -300),
    `код ${ответ.status}, ответ ${JSON.stringify(ответ.data)}, отправляли ${ждём - 300}`);
  check('названо недостачей', /недостача/.test(недостача['словами']), недостача['словами']);

  const журнал = (await админ.зов('GET', '/api/audit?action=cash_count&limit=5')).data;
  const запись = ((журнал || {}).items || [])[0];
  check('сверка попала в журнал', Boolean(запись), журнал);
  check('в журнале обе цифры, а не только разница',
    Boolean(запись) && /в ящике/.test(запись.details) && /ожидалось/.test(запись.details),
    запись && запись.details);

  console.log('\n=== 7. Следующая сверка считает от предыдущей ===');
  /*
   * Ключевое свойство: недостача не должна тянуться дальше. Пересчитали,
   * записали — и это новая точка отсчёта. Иначе одна ошибка со сдачей
   * портила бы все последующие сверки, и цифрам перестали бы верить.
   */
  const о2 = (await админ.зов('GET', '/api/cash/expected')).data;
  check('точка отсчёта — прошлая сверка', около(о2['остаток'], ждём - 300), о2['остаток']);
  /*
   * Проверяем именно СЦЕПКУ: «ожидается» = остаток с прошлой сверки плюс
   * движение с тех пор. Требовать здесь нулевого движения нельзя — в
   * демонстрационной базе продажи раскиданы по сегодняшнему дню, и часть из них
   * по времени оказывается позже нашей сверки. В жизни этого не бывает: время
   * операции ставит сервер, и оно не может убежать вперёд. А вот сцепка обязана
   * держаться всегда — на ней всё и построено.
   */
  check('ожидаемое = остаток прошлой сверки + движение с тех пор',
    около(о2['ожидается'], о2['остаток'] + о2['движение']['итого']),
    `${о2['ожидается']} против ${о2['остаток']} + ${о2['движение']['итого']}`);
  check('недостача не потянулась дальше: она осталась в прошлой сверке',
    Boolean(о2['прошлая']) && около(о2['прошлая']['расхождение'], -300)
      && !около(о2['остаток'], ждём),
    о2['прошлая']);
  check('прошлая сверка показана с её расхождением',
    о2['прошлая'] && около(о2['прошлая']['расхождение'], -300), о2['прошлая']);

  console.log('\n=== 8. Продавец сверяет, но чужих сверок не видит ===');
  const продавец = сеанс();
  check('продавец вошёл', await продавец.войти('anna', 'seller123'));
  const оП = await продавец.зов('GET', '/api/cash/expected');
  check('продавцу видно, сколько должно быть', оП.status === 200, оП.status);
  const сверкаП = await продавец.зов('POST', '/api/cash/count',
    { counted: оП.data['ожидается'], note: 'вечерняя сверка' });
  check('продавец может записать сверку', сверкаП.status === 200, сверкаП.data);
  check('история сверок продавцу закрыта',
    (await продавец.зов('GET', '/api/cash/counts')).status === 403);

  console.log('\n=== 9. История для владельца ===');
  const история = (await админ.зов('GET', '/api/cash/counts?limit=20')).data;
  const строки = (история || {}).items || [];
  // Их ровно три: первая (точка отсчёта), с недостачей и продавцовская.
  check('в истории есть все сверки', строки.length >= 3, строки.length);
  check('видно, кто считал', строки.every(с => с.user_name), строки.map(с => с.user_name));
  check('видно и ожидавшееся, и пересчитанное',
    строки.every(с => 'expected' in с && 'counted' in с), Object.keys(строки[0] || {}));
  const сНедостачей = строки.find(с => около(с.difference, -300));
  check('недостача сохранилась в истории', Boolean(сНедостачей), строки.map(с => с.difference));

  console.log('\n=== 10. Мусор не принимается ===');
  check('пустая сумма отклонена',
    (await админ.зов('POST', '/api/cash/count', {})).status === 400);
  check('отрицательная сумма отклонена',
    (await админ.зов('POST', '/api/cash/count', { counted: -5 })).status === 400);
  check('текст вместо суммы отклонён',
    (await админ.зов('POST', '/api/cash/count', { counted: 'много' })).status === 400);

  console.log(`\nИтого: ${ok} ok, ${fail} fail`);
  if (провалы.length) console.log('Провалено:\n  - ' + провалы.join('\n  - '));
  process.exit(fail ? 1 : 0);
}

main().catch(e => { console.error(e); process.exit(2); });
