'use strict';
/*
 * Скрипты установки и обновления сервера.
 *
 * Эти два файла нельзя прогнать по-настоящему: одному нужен чистый сервер
 * Ubuntu с root, другому — работающая служба systemd. Поэтому их не проверял
 * никто, и в скрипте обновления полгода жила ошибка, из-за которой он падал
 * на первой же строке: имена переменных были написаны кириллицей, а bash
 * такие имена не принимает вовсе — «ВЕТКА=main» он читает как попытку
 * запустить команду с таким названием.
 *
 * Обнаружилось это случайно и в худший момент — когда владелец собрался
 * переезжать на домен. Поэтому здесь проверяется то, что проверить МОЖНО
 * без сервера, и в первую очередь этот самый класс ошибок.
 */
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const ROOT = path.resolve(__dirname, '..');

let ok = 0, fail = 0;
const провалы = [];
const check = (имя, усл, доп) => {
  if (усл) { ok++; console.log('  ok  ' + имя); }
  else { fail++; провалы.push(имя); console.log('  FAIL ' + имя, доп === undefined ? '' : String(доп).slice(0, 300)); }
};

const скрипты = fs.readdirSync(ROOT).filter(f => f.endsWith('.sh'));

console.log('=== 1. Скрипты вообще есть ===');
check('скрипт установки на месте', скрипты.includes('УСТАНОВКА-НА-СЕРВЕР.sh'), скрипты);
check('скрипт обновления на месте', скрипты.includes('ОБНОВИТЬ-НА-СЕРВЕРЕ.sh'), скрипты);

console.log('\n=== 2. bash их понимает ===');
for (const файл of скрипты) {
  const r = spawnSync('bash', ['-n', path.join(ROOT, файл)], { encoding: 'utf8' });
  check(`${файл}: синтаксис`, r.status === 0, r.stderr);
}

console.log('\n=== 3. Имена переменных — латиницей ===');
/*
 * Главная проверка этого набора. Кириллица прекрасно работает в комментариях,
 * в сообщениях человеку и даже в именах ФУНКЦИЙ — а в именах переменных
 * не работает. Отличить одно от другого на глаз почти невозможно, поэтому
 * пусть отличает проверка.
 */
const ОПАСНЫЕ = [
  // ИМЯ=значение и ИМЯ+=(...)
  { вид: 'присваивание', re: /^\s*(?:local\s+|export\s+|declare\s+)?[A-Za-z0-9_]*[А-Яа-яЁё][А-Яа-яЁё0-9_]*\+?=/ },
  // for ИМЯ in ...
  { вид: 'цикл for', re: /^\s*for\s+[A-Za-z0-9_]*[А-Яа-яЁё][А-Яа-яЁё0-9_]*\s+in\b/ },
  /*
   * read ИМЯ
   *
   * Конец имени отмечаем не `\b`, а «дальше не буква имени». Разница
   * не теоретическая: для JavaScript кириллица — не словесный символ,
   * поэтому между «НОВЫЙ» и пробелом никакой границы слова нет, и правило
   * с `\b` молча пропускало ровно тот случай, ради которого написано.
   */
  { вид: 'read', re: /^\s*read\s+(?:-\S+\s+)*[A-Za-z0-9_]*[А-Яа-яЁё][А-Яа-яЁё0-9_]*(?![А-Яа-яЁё0-9_])/ },
];
/*
 * Смотрим не только .sh. Рабочие процессы GitHub — это тот же bash, только
 * записанный внутри yml, и капкан там ровно тот же. Проверено на себе:
 * «for попытка in 1 2 3» в шаге проверки сайта bash отверг молча, пропустил
 * весь цикл и напечатал «сайт не поднялся», ни разу никуда не постучавшись.
 * Установка при этом прошла успешно — то есть проверка не упала, а соврала,
 * и это хуже. Ключи yml (имя: значение) под правила не попадают: там
 * двоеточие, а правила требуют знак равенства.
 */
const ПРОЦЕССЫ = '.github/workflows';
const рабочиеПроцессы = fs.existsSync(path.join(ROOT, ПРОЦЕССЫ))
  ? fs.readdirSync(path.join(ROOT, ПРОЦЕССЫ))
      .filter(ф => /\.ya?ml$/.test(ф)).map(ф => `${ПРОЦЕССЫ}/${ф}`)
  : [];
for (const файл of [...скрипты, ...рабочиеПроцессы]) {
  const строки = fs.readFileSync(path.join(ROOT, файл), 'utf8').split('\n');
  const беда = [];
  строки.forEach((строка, i) => {
    if (/^\s*#/.test(строка)) return;                    // комментарий — можно как угодно
    const безСтрок = строка.replace(/"[^"]*"/g, '""').replace(/'[^']*'/g, "''");
    for (const о of ОПАСНЫЕ) {
      if (о.re.test(безСтрок)) беда.push(`строка ${i + 1} (${о.вид}): ${строка.trim().slice(0, 70)}`);
    }
  });
  check(`${файл}: нет кириллических имён переменных`, беда.length === 0, беда.slice(0, 3).join(' | '));
}

console.log('\n=== 4. Переменные, на которые ссылаются, где-то задаются ===');
/*
 * С `set -u` обращение к незаданной переменной обрывает скрипт. Именно так
 * и падало обновление: имя не присваивалось (bash отвергал строку), а дальше
 * скрипт спрашивал $ВЕТКА и умирал.
 */
const ВНЕШНИЕ = new Set(['PATH', 'HOME', 'USER', 'PWD', 'SHELL', 'LANG', 'TERM',
  'DEBIAN_FRONTEND', 'GIT_TERMINAL_PROMPT', 'GIT_ASKPASS', 'NEEDRESTART_MODE',
  'RANDOM', 'LINENO', 'BASH_SOURCE', 'FUNCNAME', 'IFS', 'OSTYPE', 'HOSTNAME']);
for (const файл of скрипты) {
  const текст = fs.readFileSync(path.join(ROOT, файл), 'utf8');
  const заданные = new Set();
  for (const m of текст.matchAll(/^\s*(?:local\s+|export\s+|declare\s+)?([A-Za-z_][A-Za-z0-9_]*)\+?=/gm)) {
    заданные.add(m[1]);
  }
  for (const m of текст.matchAll(/^\s*for\s+([A-Za-z_][A-Za-z0-9_]*)\s+in\b/gm)) заданные.add(m[1]);
  const неизвестные = new Set();
  for (const m of текст.matchAll(/\$\{?([A-Za-z_][A-Za-z0-9_]*)[}:\s/]/g)) {
    const имя = m[1];
    if (заданные.has(имя) || ВНЕШНИЕ.has(имя) || /^\d+$/.test(имя)) continue;
    неизвестные.add(имя);
  }
  check(`${файл}: все переменные откуда-то берутся`, неизвестные.size === 0,
    [...неизвестные].join(', '));
}

console.log('\n=== 5. Файлы, которые скрипты обещают, существуют ===');
/*
 * Скрипт установки печатает владельцу команды со ссылками на файлы системы.
 * Файл переименовали — владелец получает «No such file» в тот момент, когда
 * ему меньше всего хочется разбираться.
 */
const обещанные = new Set();
for (const файл of [...скрипты, 'ПЕРЕЕЗД-НА-ДОМЕН.md', 'ХОСТИНГ.md']) {
  const п = path.join(ROOT, файл);
  if (!fs.existsSync(п)) continue;
  const текст = fs.readFileSync(п, 'utf8');
  /*
   * Строчная буква в начале имени тоже считается: короткий вход в установку
   * называется install.sh, и раньше он не попадал под эту проверку вовсе.
   */
  for (const m of текст.matchAll(/(?:src\/[\wА-Яа-яЁё-]+\.js|[A-Za-zА-Яа-яЁё][\wА-Яа-яЁё-]*\.sh)/g)) {
    обещанные.add(m[0]);
  }
}
for (const файл of [...обещанные].sort()) {
  check(`есть ${файл}`, fs.existsSync(path.join(ROOT, файл)));
}

console.log('\n=== 6. Обновление обещает откат — и умеет его ===');
const обн = fs.readFileSync(path.join(ROOT, 'ОБНОВИТЬ-НА-СЕРВЕРЕ.sh'), 'utf8');
check('снимает копию до обновления', /VACUUM INTO/.test(обн));
check('копия делается ДО git checkout',
  обн.indexOf('VACUUM INTO') < обн.indexOf('git checkout'), 'порядок нарушен');
check('проверяет, что система поднялась', /api\/ping/.test(обн));
check('возвращает прежнюю версию при неудаче',
  /git checkout[^\n]*"\$WAS"/.test(обн), 'отката нет');
check('говорит человеку, куда смотреть при сбое', /journalctl/.test(обн));

const уст = fs.readFileSync(path.join(ROOT, 'УСТАНОВКА-НА-СЕРВЕР.sh'), 'utf8');
console.log('\n=== 7. Установка не забывает обязательного ===');
check('включает строгий порт', /ASHER_STRICT_PORT=1/.test(уст));
check('включает доверие прокси', /ASHER_TRUST_PROXY=1/.test(уст));
check('не открывает наружу порт системы', !/ufw allow 3000/.test(уст));
check('ставит владельцу файлы под нужным пользователем', /chown -R/.test(уст));
check('берёт основную ветку, а не рабочую',
  !/BRANCH="\$\{3:-claude\//.test(уст), 'по умолчанию тянется рабочая ветка');

console.log('\n=== 8. Короткая команда установки жива и совпадает с инструкцией ===');
/*
 * Ради этой команды и заведён install.sh. Консоль сервера у хостинга
 * открывается в браузере: вставки в ней нет, раскладка только английская —
 * «УСТАНОВКА-НА-СЕРВЕР.sh» там набрать нечем, и владелец упирается в чёрный
 * экран, имея на руках готовую систему. Поэтому проверяем не только наличие
 * файла, но и то, что инструкция зовёт именно его и что набрать её можно
 * вслепую на английской раскладке.
 */
check('короткий вход в установку на месте', скрипты.includes('install.sh'), скрипты);
const переезд = fs.readFileSync(path.join(ROOT, 'ПЕРЕЕЗД-НА-ДОМЕН.md'), 'utf8');
const хостинг = fs.readFileSync(path.join(ROOT, 'ХОСТИНГ.md'), 'utf8');
const строкаКоманды = переезд.split('\n').find(с => /^curl\b.*install\.sh/.test(с.trim()));
check('инструкция владельца зовёт именно его', Boolean(строкаКоманды),
  'в ПЕРЕЕЗД-НА-ДОМЕН.md нет строки curl … install.sh');
check('команда набирается на английской раскладке',
  Boolean(строкаКоманды) && !/[А-Яа-яЁё]/.test(строкаКоманды), строкаКоманды);
check('и передаёт домен установщику',
  Boolean(строкаКоманды) && /\|\s*bash\s+-s\s+\S+/.test(строкаКоманды), строкаКоманды);
check('справочник по хостингу говорит то же самое', /install\.sh/.test(хостинг));
const вход = fs.readFileSync(path.join(ROOT, 'install.sh'), 'utf8');
check('короткий вход зовёт настоящий установщик',
  /УСТАНОВКА-НА-СЕРВЕР\.sh/.test(вход), 'install.sh ведёт куда-то не туда');
check('короткий вход не делает установку сам',
  !/systemctl|caddy|ufw/i.test(вход), 'логика установки расползлась по двум файлам');

console.log('\n=== 9. Наборы берут порт у запускающего, а не вписывают в себя ===');
/*
 * Запускающий поднимает систему на свободном порту: если 3122 занят — своим
 * же сервером разработчика или прошлым прогоном, не успевшим закрыться, —
 * он возьмёт 3123 и передаст его наборам в BASE. Набор с вписанным адресом
 * в этот момент стучится в пустоту и падает с «connection refused», хотя всё
 * исправно. Так и случилось: два браузерных набора падали не по своей вине,
 * и полчаса ушло на поиск причины не там, где она была.
 *
 * Строка `const BASE = process.env.BASE || 'http://127.0.0.1:3122'` — это
 * не вписанный адрес, а запасной вариант для запуска набора в одиночку.
 * Поэтому ищем адрес там, где он используется, а не в объявлении.
 */
for (const файл of fs.readdirSync(__dirname).filter(ф => /\.js$/.test(ф) && ф !== 'ПРОВЕРИТЬ.js')) {
  const строки = fs.readFileSync(path.join(__dirname, файл), 'utf8').split('\n');
  const беда = [];
  строки.forEach((строка, i) => {
    if (/^\s*(\/\/|\*|\/\*)/.test(строка)) return;             // комментарий — можно
    if (/BASE\s*=\s*process\.env\.BASE/.test(строка)) return;  // запасной вариант — можно
    if (/127\.0\.0\.1:31\d\d/.test(строка)) {
      беда.push(`строка ${i + 1}: ${строка.trim().slice(0, 62)}`);
    }
  });
  check(`${файл}: адрес не вписан в набор`, беда.length === 0, беда.slice(0, 2).join(' | '));
}

console.log('\n=== 10. Файлы для Windows хранятся правильно ===');
/*
 * .bat и .ps1 живут на компьютере магазина, и переводы строк им нужны
 * windows-овские — это записано в .gitattributes. Но правило описывает, каким
 * файл выдаётся, а в самом хранилище он должен лежать с обычными переводами.
 * Если туда попал windows-вариант, git будет считать файл изменённым вечно:
 * на сервере это уже случилось и остановило обновление системы — скрипт
 * обновления справедливо отказался затирать «чужие правки», которых не было.
 * Заметить такое глазами нельзя: знак конца строки невидим.
 */
{
  // quotepath=false — иначе git печатает кириллические имена кодами вида
  // \320\241\320\242, и понять, какой файл провалился, нельзя.
  const r = spawnSync('git', ['-c', 'core.quotepath=false', 'ls-files', '--eol',
    '--', '*.bat', '*.ps1'], { cwd: ROOT, encoding: 'utf8' });
  if (r.status !== 0) {
    check('git доступен, чтобы проверить переводы строк', false, (r.stderr || '').trim());
  } else {
    const строки = r.stdout.split('\n').filter(Boolean);
    check('файлы для Windows вообще есть', строки.length > 0, r.stdout);
    for (const строка of строки) {
      /*
       * Строка выглядит так:  i/lf  w/crlf  attr/text eol=crlf <TAB> путь
       * Имя отделено табуляцией, а не пробелом, — и это важно: в графе
       * с правилом («attr/text eol=crlf») пробел есть, и разбор по пробелам
       * приносит в имя файла половину этой графы.
       */
      const [графы, имя] = строка.split('\t');
      const вХранилище = (графы.match(/\bi\/(\S+)/) || [])[1];
      const вПапке = (графы.match(/\bw\/(\S+)/) || [])[1];
      if (!имя || !вХранилище) continue;
      check(`${имя}: в хранилище обычные переводы строк`,
        вХранилище === 'lf' || вХранилище === 'none',
        `лежит как ${вХранилище}, а должно lf — иначе файл вечно «изменён»`);
      check(`${имя}: в рабочую папку выдаётся windows-вариант`,
        вПапке === 'crlf' || вПапке === 'none', `выдаётся как ${вПапке}`);
    }
  }
}

console.log(`\nИтого: ${ok} ok, ${fail} fail`);
if (провалы.length) console.log('Провалено:\n  - ' + провалы.join('\n  - '));
process.exit(fail ? 1 : 0);
