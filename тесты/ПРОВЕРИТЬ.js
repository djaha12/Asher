function свободныйПорт(от = 3122) {
  for (let p = от; p < от + 200; p++) {
    const s = spawnSync(process.execPath, ['-e', `
      const net = require('node:net');
      const srv = net.createServer();
      srv.once('error', () => process.exit(1));
      srv.listen(${p}, '127.0.0.1', () => srv.close(() => process.exit(0)));
    `]);
    if (s.status === 0) return p;
  }
  throw new Error('не нашёл свободный порт');
}

function естьPlaywright() {
  // Спрашиваем ровно так же, как это делают сами наборы (тесты/браузер.js):
  // локально, потом глобально. Иначе сводка соврёт про пропуск.
  try { require.resolve('playwright', { paths: [ROOT, __dirname] }); return true; } catch { /* дальше */ }
  try {
    const корень = spawnSync('npm', ['root', '-g'], { encoding: 'utf8' }).stdout.trim();
    require.resolve(path.join(корень, 'playwright'));
    return true;
  } catch { return false; }
}

function живПорт(порт) {
  return new Promise(res => {
    const s = net.connect(порт, '127.0.0.1');
    s.once('connect', () => { s.destroy(); res(true); });
    s.once('error', () => res(false));
    setTimeout(() => { s.destroy(); res(false); }, 300);
  });
}

async function ждатьСервер(порт, секунд = 20) {
  for (let i = 0; i < секунд * 5; i++) {
    if (await живПорт(порт)) return true;
    await new Promise(r => setTimeout(r, 200));
  }
  return false;
}

(async () => {
  /*
   * Замок на один прогон. Первое, что делает прогон, — стирает папку вывода
   * вместе с базой. Если запустить второй, он вынет базу из-под первого:
   * тот начнёт получать «Не авторизован» и обрывы по времени в случайных
   * местах, и полдня уйдёт на поиск несуществующей ошибки в системе.
   */
  const замок = path.join(__dirname, '.идёт-проверка');
  try {
    const прежний = Number(fs.readFileSync(замок, 'utf8'));
    const возраст = Date.now() - fs.statSync(замок).mtimeMs;
    process.kill(прежний, 0);          // бросит, если такого процесса уже нет
    // Номер процесса система переиспользует, поэтому одной проверки мало:
    // брошенный замок мог «ожить» на чужом процессе и запереть нас навсегда.
    // Прогон длиннее получаса не бывает — значит замок просто забыт.
    if (возраст < 30 * 60000) {
      console.error(`\nПроверка уже идёт (процесс ${прежний}). Дождитесь её окончания.`);
      console.error(`Если она зависла — снимите её и удалите файл ${замок}\n`);
      process.exit(1);
    }
  } catch { /* замка нет или процесс мёртв — можно работать */ }
  fs.mkdirSync(__dirname, { recursive: true });
  fs.writeFileSync(замок, String(process.pid));
  process.on('exit', () => { try { fs.unlinkSync(замок); } catch { /* уже убрали */ } });

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(DATA, { recursive: true });

  const БАЗА = path.join(DATA, 'проверка.db');
  const окружение = {
    ...process.env,
    ASHER_DB: БАЗА,
    ASHER_DATA: DATA,
    NO_OPEN: '1',
    // Прокси в этой среде перехватывает даже 127.0.0.1 — тесты стучатся
    // напрямую, иначе половина запросов уходит в никуда.
    NO_PROXY: '*', no_proxy: '*',
  };

  console.log('Готовлю отдельную базу с демонстрационными данными…');
  const seed = spawnSync(process.execPath, [path.join('src', 'seed.js'), '--reset'],
    { cwd: ROOT, env: окружение, encoding: 'utf8' });
  if (seed.status !== 0) {
    console.error('Не удалось наполнить базу:\n' + (seed.stderr || seed.stdout));
    process.exit(1);
  }

  const порт = свободныйПорт();
  окружение.PORT = String(порт);
  окружение.BASE = `http://127.0.0.1:${порт}`;

  /*
   * Сервер поднимаем заново перед каждым набором. Это не перестраховка.
   *
   * Защита от подбора пароля считает неудачные попытки по адресу, и порог
   * намеренно высокий — за одним внешним адресом стоит весь магазин. Но все
   * наборы приходят с одного и того же 127.0.0.1, и за прогон неудачных
   * попыток набирается больше сотни: часть наборов проверяет отказы намеренно.
   * Защита срабатывает — правильно срабатывает — и следующий набор не может
   * войти. Мы полдня искали бы поломку там, где её нет.
   *
   * Счётчики живут в памяти, база — на диске, поэтому перезапуск обнуляет
   * ровно счётчики и ничего больше. Стоит это две секунды на набор.
   */
  console.log(`Поднимаю сервер на порту ${порт}…\n`);
  let сервер = null;
  const стоп = () => { try { if (сервер) сервер.kill(); } catch { /* уже мёртв */ } };
  process.on('exit', стоп);
  process.on('SIGINT', () => { стоп(); process.exit(130); });

  async function поднятьСервер() {
    стоп();
    // Порт освобождается не мгновенно — иначе новый сервер упрётся в старый.
    for (let i = 0; i < 40 && await живПорт(порт); i++) await new Promise(r => setTimeout(r, 100));
    сервер = spawn(process.execPath, ['server.js'],
      { cwd: ROOT, env: окружение, stdio: 'ignore' });
    return ждатьСервер(порт);
  }

  if (!await поднятьСервер()) {
    стоп();
    console.error('Сервер не поднялся. Запустите вручную: npm start');
    process.exit(1);
  }

  const браузерЕсть = естьPlaywright();
  if (!браузерЕсть) {
    console.log('Playwright не установлен — экранные проверки пропускаю.');
    console.log('Чтобы их включить:  npm i -D playwright && npx playwright install chromium\n');
  }

  const итоги = [];
  for (const н of НАБОРЫ) {
    const имя = н.файл.replace(/\.js$/, '');
    if (н.браузер && !браузерЕсть) {
      итоги.push({ имя, что: н.что, статус: 'пропущен' });
      console.log(`⊘  ${имя.padEnd(20)} ${н.что} — нужен Playwright`);
      continue;
    }
    // Свежий сервер на каждый набор: см. пояснение у поднятьСервер().
    if (!н.свой_сервер && !await поднятьСервер()) {
      итоги.push({ имя, что: н.что, статус: 'fail', счёт: 'сервер не поднялся', вывод: '' });
      console.log(`   ${имя.padEnd(20)} ${н.что} … ✗ сервер не поднялся`);
      continue;
    }
    process.stdout.write(`   ${имя.padEnd(20)} ${н.что} … `);
    const r = spawnSync(process.execPath, [path.join(__dirname, н.файл)],
      { cwd: ROOT, env: окружение, encoding: 'utf8', timeout: 15 * 60 * 1000 });
    const вывод = (r.stdout || '') + (r.stderr || '');
    const сводка = вывод.match(/Итого:\s*(\d+)\s*ok,\s*(\d+)\s*fail/);
    const успех = r.status === 0 && (!сводка || Number(сводка[2]) === 0);
    const счёт = сводка ? `${сводка[1]} проверок` : (успех ? 'пройден' : 'сбой');
    итоги.push({ имя, что: н.что, статус: успех ? 'ok' : 'fail', счёт, вывод });
    console.log(успех ? `✓ ${счёт}` : `✗ ${счёт}`);
    if (!успех) {
      // Показываем только суть: полный вывод набора — это сотни строк.
      const строки = вывод.split('\n').filter(l => /FAIL|Сбой|Error|error:|Timeout/.test(l));
      for (const l of строки.slice(0, 6)) console.log('       ' + l.trim());
      /*
       * Полный вывод — в файл. Часть сбоев видна только в общем прогоне
       * (наборы идут по одной базе и по очереди), а поодиночке набор
       * проходит. Совет «запустите его отдельно» в таком случае никуда
       * не ведёт, а разбираться приходится по шести строкам из середины.
       */
      try {
        const куда = path.join(OUT, `сбой-${имя}.log`);
        fs.mkdirSync(OUT, { recursive: true });
        fs.writeFileSync(куда, вывод);
        console.log('       весь вывод: ' + path.relative(ROOT, куда));
      } catch { /* не смогли — не беда, суть уже напечатана */ }
    }
  }

  стоп();

  const ok = итоги.filter(i => i.статус === 'ok');
  const fail = итоги.filter(i => i.статус === 'fail');
  const skip = итоги.filter(i => i.статус === 'пропущен');
  const всего = ok.reduce((s, i) => s + (parseInt(i.счёт, 10) || 0), 0);

  console.log('\n' + '─'.repeat(60));
  console.log(`Наборов пройдено: ${ok.length}, со сбоями: ${fail.length}` +
    (skip.length ? `, пропущено: ${skip.length}` : ''));
  console.log(`Всего проверок:   ${всего}`);
  if (fail.length) {
    console.log('\nСбои:');
    for (const f of fail) console.log(`  ✗ ${f.имя} — ${f.что}`);
    console.log('\nПодробности — запустите набор отдельно, например:');
    console.log(`  BASE=http://127.0.0.1:${порт} node тесты/${fail[0].имя}.js`);
  }
  console.log('─'.repeat(60));
  process.exit(fail.length ? 1 : 0);
})();
