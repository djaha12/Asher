/*
 * Прогон всех проверок: node тесты/ПРОВЕРИТЬ.js
 *
 * Зачем это лежит в проекте. Система считает деньги магазина, и почти всё, что
 * в ней есть, доказано не рассуждением, а проверкой: продажа, возврат, обмен,
 * долги, комплекты, расчёты с поставщиками, права продавца, защита входа,
 * обмен с 1С. Пока проверки живут где-то отдельно, любая будущая правка — и уж
 * тем более переезд на другой хостинг — делается вслепую. Здесь они рядом
 * с кодом, и любой, кто возьмётся за систему после нас, может одной командой
 * убедиться, что ничего не рассыпалось.
 *
 * Что происходит при запуске: создаётся отдельная база с демонстрационными
 * данными (ваша не трогается), поднимается сервер на свободном порту, наборы
 * прогоняются по очереди, в конце — сводка. Всё временное складывается
 * в тесты/.вывод и в git не попадает.
 *
 * Наборы с браузером требуют Playwright (npm i -D playwright). Если его нет,
 * они честно помечаются как пропущенные, а остальные идут своим ходом.
 */
