'use strict';
/*
 * Отметка устройства для проверок.
 *
 * Система пускает только с известных устройств: незнакомое ждёт разрешения
 * владельца. Это и есть защита от утёкшего пароля, и обойти её удалением
 * заголовка нельзя — иначе она ничего бы не защищала.
 *
 * Значит и проверки должны называть себя устройством, как это делает
 * настоящее приложение. Ключ у всех наборов один: первый вход каждого
 * сотрудника доверяет его сам (так же, как в жизни доверяется телефон
 * продавца, которому владелец только что выдал карточку подключения),
 * и дальше все наборы работают с уже разрешённого устройства.
 *
 * Подключается одной строкой:  require('./устройство');
 */
// Только латиница и цифры: заголовок HTTP не принимает кириллицу.
const КЛЮЧ = process.env.ASHER_TEST_DEVICE || 'asher-test-device';

const настоящийFetch = globalThis.fetch;
globalThis.fetch = function (url, opts = {}) {
  const headers = new Headers(opts.headers || {});
  if (!headers.has('X-Asher-Device')) headers.set('X-Asher-Device', КЛЮЧ);
  return настоящийFetch(url, { ...opts, headers });
};

module.exports = { КЛЮЧ };
