'use strict';
/*
 * Как система понимает, что ищут, — одинаково во всех разделах.
 *
 * Раньше каждый раздел искал по-своему, и все — буквально: запрос целиком,
 * как набран. «Алена» не находила «Алёну», «Садыкова Айжан» — «Айжан
 * Садыкову», «AS00120» — «AS-00120», а чек по имени клиента не находился
 * вовсе. Человек не должен угадывать, как именно записано в базе. Здесь
 * правила одни на всю систему:
 *
 *   — большие и маленькие буквы не различаем, русские тоже;
 *   — «е» и «ё» — одна буква; кыргызские «ү», «ө», «ң» находятся по «у»,
 *     «о», «н»: на русской раскладке их нет, и «Гүлнара» набирают «Гулнара»;
 *   — несколько слов — в любом порядке и в любых полях: «кольцо 585»,
 *     «Айжан Садыкова», «Садыкова Айжан» — всё находит;
 *   — артикул и номер находятся без чёрточек: «as00120» — это «AS-00120»;
 *   — телефон — в любом виде: «0555 12-34-56», «+996 555 123456», «123456».
 *
 * А если по набранному пусто — пробуем ещё, по порядку:
 *   — без окончаний: «цепь» находит «цепочку», «кольца» — «кольцо»,
 *     а «серёжки» — «серьги» (как говорят и как записано — по словарю);
 *   — в другой раскладке: «rjkmwj» — это «кольцо», «фы-00120» — «AS-00120».
 * Именно запасным ходом, а не всегда: иначе «Мария» находила бы и «Марину».
 *
 * Точно такие же правила продублированы для экрана в public/js/ui.js
 * (ui.поиск): разделы, которые отбирают уже загруженный список, должны
 * находить то же самое, что и сервер.
 */

// Буквы, которые пишут по-разному, а имеют в виду одно.
const ЗАМЕНЫ = { 'ё': 'е', 'ү': 'у', 'ө': 'о', 'ң': 'н' };

function свернуть(s) {
  if (s === null || s === undefined) return '';
  return String(s).toLowerCase().replace(/[ёүөң]/g, ch => ЗАМЕНЫ[ch]);
}

// Без разделителей: «AS-00120», «AS 00120» и «as00120» — одно и то же.
// Перевод строки не трогаем — он отделяет одно поле от другого.
const сжать = s => s.replace(/[ \t\u00a0\u202f\-\u2013\u2014./_]/g, '');

/*
 * Суть номера телефона: цифры без кода страны и без местного нуля.
 * «0555 12-34-56», «+996 555 123456» и «555123456» дают одно «555123456»,
 * а оно есть внутри любой записи этого номера.
 */
function ядроНомера(s, мин) {
  const сырой = String(s);
  let d = сырой.replace(/\D/g, '');
  if (d.startsWith('00996')) d = d.slice(2);
  if (d.startsWith('996') && (d.length >= 9 || /^\s*\+/.test(сырой))) d = d.slice(3);
  else if (d.startsWith('0') && d.length > 3) d = d.slice(1);
  return мин > 0 && d.length >= мин ? d : '';
}

const ПОХОЖ_НА_НОМЕР = /^[\d\s()+\-.]+$/;

/*
 * Разобрать запрос: слова и номер. минЦифр — сколько цифр нужно, чтобы
 * искать по телефону: в клиентах хватает трёх, а в чеках «123» — это
 * скорее номер чека, и телефоны с «123» там только мешали бы.
 */
function разобрать(запрос, минЦифр = 3) {
  const текст = свернуть(запрос).trim();
  const слова = [...new Set(текст.split(/\s+/).filter(Boolean))].slice(0, 8).map(w => ({
    w,
    сжато: /\d/.test(w) ? сжать(w) : '',
    ядро: ПОХОЖ_НА_НОМЕР.test(w) ? ядроНомера(w, минЦифр) : '',
  }));
  const номер = текст && ПОХОЖ_НА_НОМЕР.test(текст) ? ядроНомера(текст, минЦифр) : '';
  return { текст, слова, номер };
}

// Подходит ли запись: каждое слово нашлось хотя бы в одном поле.
function подходит(разбор, телефон, поля) {
  const тел = телефон ? String(телефон).replace(/\D/g, '') : '';
  if (разбор.номер && тел.includes(разбор.номер)) return true;
  if (!разбор.слова.length) return true;
  // Поля склеиваем и сворачиваем разом: на складе в пятнадцать тысяч изделий
  // это вдвое быстрее, чем сворачивать каждое поле. null в join даёт пустоту.
  const текст = свернуть(поля.join('\n'));
  let сжатый = null;
  return разбор.слова.every(с => {
    if (текст.includes(с.w)) return true;
    if (с.ядро && тел.includes(с.ядро)) return true;
    if (с.сжато) {
      if (сжатый === null) сжатый = сжать(текст);
      return сжатый.includes(с.сжато);
    }
    return false;
  });
}

/*
 * Для SQL: nmatch(запрос, минЦифр, телефон, поле1, поле2, …). База зовёт
 * функцию на каждой строке с одним и тем же запросом — разбираем его один раз.
 */
let последний = { ключ: null, разбор: null };
function совпадаетSQL(запрос, минЦифр, телефон, поля) {
  const ключ = минЦифр + '\u0001' + запрос;
  if (последний.ключ !== ключ) последний = { ключ, разбор: разобрать(запрос, Number(минЦифр) || 0) };
  return подходит(последний.разбор, телефон, поля) ? 1 : 0;
}

// Если нужно сравнить в JS то, что уже загружено.
function совпадает(запрос, { телефон = '', поля = [], минЦифр = 3 } = {}) {
  return подходит(разобрать(запрос, минЦифр), телефон, поля);
}

/*
 * Основа русского слова — без окончания: «цепь» → «цеп» (находит «цепочку»),
 * «кольца» → «кольц», «золотое» → «золот». Срезаем одну конечную гласную
 * (или ь, й), вторую — только у длинных слов. Артикулы, номера и латиницу
 * не трогаем.
 */
const КОНЕЦ = /[аяоеиыуюьй]$/;
function основа(w) {
  if (w.length < 4 || !/^[а-я]+$/.test(w) || !КОНЕЦ.test(w)) return '';
  let о = w.slice(0, -1);
  if (КОНЕЦ.test(о) && о.length - 1 >= 5) о = о.slice(0, -1);
  return о.length >= 3 ? о : '';
}

/*
 * Как украшения называют в разговоре — и как они записаны в каталоге.
 * «Серёжки» — это «серьги», а не другое слово с другим окончанием: срезанием
 * окончаний их не свести, поэтому — словарём. Ищем по нему тоже запасным ходом.
 */
const РАЗГОВОРНОЕ = {
  сережки: 'серьги', сережка: 'серьги', сережку: 'серьги', цепочка: 'цепь', цепочку: 'цепь',
  цепочки: 'цепь', колечко: 'кольцо', колечки: 'кольца', кулон: 'подвеска', кулоны: 'подвески',
  кулончик: 'подвеска', брошка: 'брошь', брошку: 'брошь', часики: 'часы', браслетик: 'браслет',
};

// Одно слово: как записано в каталоге и без окончания; пусто — если нечего менять.
function срезать(w) {
  const с = РАЗГОВОРНОЕ[w] || w;
  return основа(с) || (с !== w ? с : '');
}

// Весь запрос без окончаний; пусто — если срезать нечего.
function безОкончаний(запрос) {
  const слова = свернуть(запрос).trim().split(/\s+/).filter(Boolean);
  const срезано = слова.map(w => срезать(w) || w);
  return срезано.join(' ') !== слова.join(' ') ? срезано.join(' ') : '';
}

/*
 * Та же клавиша в другой раскладке. Продавец набирает артикул, а клавиатура
 * осталась русской — выходит «фы-00120» вместо «AS-00120»; сканер-клавиатура
 * путается точно так же. Смесь букв не трогаем: это не опечатка раскладки.
 */
const EN = "`qwertyuiop[]asdfghjkl;'zxcvbnm,.";
const RU = 'ёйцукенгшщзхъфывапролджэячсмитьбю';

function другаяРаскладка(запрос) {
  const s = String(запрос || '').toLowerCase();
  const лат = /[a-z]/.test(s);
  const кир = /[а-яё]/.test(s);
  if (лат === кир) return '';
  const [из, в] = лат ? [EN, RU] : [RU, EN];
  let out = '';
  for (const ch of s) {
    const i = из.indexOf(ch);
    out += i >= 0 ? в[i] : ch;
  }
  return out.trim() && out !== s ? out : '';
}

/*
 * Что пробовать, если по набранному пусто, — по порядку. «раскладка» —
 * по чему искали на самом деле, если раскладку пришлось исправить: экран
 * покажет это у поля, иначе кольца по запросу «rjkmwj» выглядели бы загадкой.
 */
function запасныеХоды(запрос) {
  const ходы = [];
  const срезано = безОкончаний(запрос);
  if (срезано) ходы.push({ search: срезано, раскладка: '' });
  const иначе = другаяРаскладка(запрос);
  if (иначе) {
    ходы.push({ search: иначе, раскладка: иначе });
    const иначеСрезано = безОкончаний(иначе);
    if (иначеСрезано) ходы.push({ search: иначеСрезано, раскладка: иначе });
  }
  return ходы;
}

/*
 * Выполнить поиск; если по набранному пусто — запасными ходами. Ничего не
 * нашлось и так — отвечаем как есть.
 */
function искатьСЗапасом(query, выполнить, пусто = r => !(r && r.items && r.items.length)) {
  const r = выполнить(query);
  const поиск = String((query && query.search) || '').trim();
  if (!поиск || !пусто(r)) return r;
  for (const ход of запасныеХоды(поиск)) {
    const r2 = выполнить({ ...query, search: ход.search });
    if (!пусто(r2)) return ход.раскладка ? { ...r2, раскладка: ход.раскладка } : r2;
  }
  return r;
}

module.exports = {
  свернуть, сжать, ядроНомера, разобрать, подходит, совпадает, совпадаетSQL,
  основа, срезать, безОкончаний, другаяРаскладка, запасныеХоды, искатьСЗапасом,
};
