'use strict';
/*
 * Двойники — одно и то же, заведённое дважды: «AS-001» и «as-001»,
 * «Азия Голд» и «азия голд».
 *
 * Большие и маленькие буквы система теперь не различает — ни в поиске, ни
 * при проверке повтора, — и нового двойника уже не завести. Но раньше
 * «as-001» заводился рядом с «AS-001», а «азия голд» — рядом с «Азия Голд»,
 * и такие пары могли остаться в базе. Здесь их находим по тем же правилам,
 * по которым система теперь сравнивает (поиск.свернуть); лишние пробелы —
 * тоже не разница.
 *
 * Только читаем — ничего не меняем. Что из двух оставить, решает владелец:
 * бывает, что это одно изделие, заведённое дважды, а бывает — два разных
 * с одним артикулом.
 *
 * Где это видно:
 *   — владельцу на Главной, среди тревог, поимённо (api/analytics.js);
 *   — в отчёте обновления сервера — одни числа. Журнал обновления лежит
 *     в открытом репозитории и виден всем, поэтому ни артикулов, ни
 *     названий туда не пишем. Запуск: node src/двойники.js путь/к/asher.db
 *     — база открывается только на чтение.
 */
const { свернуть } = require('./поиск');

const ключ = s => свернуть(String(s === null || s === undefined ? '' : s).trim().replace(/\s+/g, ' '));

// Записи с одним ключом — группой; одиночки не нужны.
function группы(записи, поле) {
  const по = new Map();
  for (const з of записи) {
    const к = ключ(з[поле]);
    if (!к) continue;
    if (!по.has(к)) по.set(к, []);
    по.get(к).push(з);
  }
  return [...по.values()].filter(г => г.length > 1);
}

/*
 * Артикул у изделий и комплектов общий: касса и сканер ищут по нему и там,
 * и там (так же проверяет api/sets.js), — поэтому и двойников ищем вместе.
 */
function найти(db) {
  const артикулы = db.prepare('SELECT id, sku, name, status FROM products ORDER BY id').all()
    .map(p => ({ ...p, вид: 'изделие' }));
  const естьКомплекты = db.prepare(`SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'product_sets'`).get();
  if (естьКомплекты) {
    for (const к of db.prepare('SELECT id, sku, name FROM product_sets ORDER BY id').all()) {
      артикулы.push({ ...к, вид: 'комплект' });
    }
  }
  return {
    артикулы: группы(артикулы, 'sku'),
    поставщики: группы(db.prepare('SELECT id, name FROM suppliers ORDER BY id').all(), 'name'),
    категории: группы(db.prepare('SELECT id, name FROM categories ORDER BY sort, id').all(), 'name'),
    точки: группы(db.prepare('SELECT id, name FROM stores ORDER BY sort, id').all(), 'name'),
  };
}

// Для отчёта обновления: сколько, без единого названия.
function отчёт(н) {
  const виды = [['артикулы', н.артикулы], ['поставщики', н.поставщики],
    ['категории', н.категории], ['точки продаж', н.точки]];
  if (виды.every(([, г]) => !г.length)) {
    return '   Двойников нет: ни артикулов, ни поставщиков, ни категорий, ни точек, записанных дважды.';
  }
  return ['   Записано дважды (одно и то же разными буквами):',
    ...виды.map(([имя, г]) => `     ${(имя + ':').padEnd(14)}${г.length}`
      + (г.length ? ` (записей: ${г.reduce((с, x) => с + x.length, 0)})` : '')),
    '   Какие именно — владельцу на Главной. Здесь без названий: журнал обновления виден всем.',
  ].join('\n');
}

module.exports = { найти, отчёт };

if (require.main === module) {
  try {
    const { DatabaseSync } = require('node:sqlite');
    const db = new DatabaseSync(process.argv[2], { readOnly: true });
    const н = найти(db);
    db.close();
    console.log(отчёт(н));
  } catch (e) {
    console.log('   Проверить не удалось: ' + e.message);
    process.exitCode = 1;
  }
}
