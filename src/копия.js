'use strict';
/*
 * Резервная копия: сборка архива и ключ для автоматического скачивания.
 *
 * Копии, которые система делает сама, лежат на том же диске, что и база.
 * От сбоя диска, пропавшего сервера и неоплаченного хостинга они не спасают
 * вовсе — а именно так магазины и теряют учёт. Спасает только копия в другом
 * месте: на компьютере магазина, на флешке, в облаке.
 *
 * Кнопка «Скачать резервную копию» это умеет, но требует человека, который
 * помнит про неё каждый день. Люди не помнят — и это не упрёк, а свойство
 * людей. Поэтому здесь заведён ключ: компьютер магазина скачивает копию сам,
 * по расписанию, без пароля владельца.
 *
 * Ключ — не пароль и правами сотрудника не обладает: он открывает ровно один
 * адрес, скачивание копии, и ничего больше. Но копия — это все данные
 * магазина целиком, поэтому обращаться с ним надо как с ключом от сейфа:
 * он показывается один раз, живёт в файле задания на компьютере магазина,
 * и его в любую минуту можно отозвать, не трогая ничьи пароли.
 */
const crypto = require('node:crypto');
const { getSetting, setSetting, audit } = require('./db');

/*
 * Знаки без двойников: ключ иногда всё-таки переписывают глазами, и «l» / «1»
 * или «O» / «0» в такой момент стоят получаса разбирательств. 32 знака из
 * 32-буквенного алфавита — это 160 бит, перебрать нельзя.
 */
const АЛФАВИТ = 'abcdefghijkmnpqrstuvwxyz23456789';
const ДЛИНА = 32;

function создатьКлюч() {
  let ключ = '';
  for (const b of crypto.randomBytes(ДЛИНА)) ключ += АЛФАВИТ[b % АЛФАВИТ.length];
  setSetting('backup_key', ключ);
  return ключ;
}

function убратьКлюч() { setSetting('backup_key', ''); }

function ключЕсть() { return Boolean(getSetting('backup_key')); }

/*
 * Сравниваем за постоянное время. Обычное === возвращается тем быстрее, чем
 * раньше не совпал знак, и по времени ответа ключ подбирается знак за знаком,
 * не перебирая всё. Длину проверяем отдельно: timingSafeEqual на разных
 * длинах не сравнивает, а падает.
 */
function ключВерен(данный) {
  const свой = String(getSetting('backup_key') || '');
  if (!свой || !данный) return false;
  const a = Buffer.from(String(данный), 'utf8');
  const b = Buffer.from(свой, 'utf8');
  if (a.length !== b.length) return false;
  return crypto.timingSafeEqual(a, b);
}

/*
 * Собрать и отдать архив.
 *
 * В архив кладём И базу, И фотографии. Когда-то отдавалась одна база, а рядом
 * было написано «вся система целиком» — и это была неправда: фотографии
 * изделий и сканы сертификатов лежат отдельными файлами. Владелец, потерявший
 * компьютер, восстановил бы каталог без единого снимка и узнал бы об этом
 * в худший из возможных моментов.
 */
async function отдатьКопию(res, { userId = null, откуда = 'вручную' } = {}) {
  const { streamZip, listFiles } = require('./zip');
  const { MEDIA_DIR } = require('./db');

  const snapshot = require('./sync').makeBackupNow();
  const entries = [{ name: 'data/asher.db', file: snapshot }];
  // Фотографии кладём рядом с базой, сохраняя структуру папок: так архив
  // распаковывается прямо поверх папки системы.
  for (const f of listFiles(MEDIA_DIR)) {
    entries.push({ name: 'data/images/' + f.name, file: f.file });
  }
  // Короткая записка внутрь архива: через полгода никто не вспомнит,
  // что это за файл и что с ним делать.
  entries.push({
    name: 'КАК-ВОССТАНОВИТЬ.txt',
    data: Buffer.from(
      'Резервная копия — ' + (getSetting('store_name') || 'учётная система') + '\r\n' +
      'Снята: ' + new Date().toLocaleString('ru-RU') + '\r\n\r\n' +
      'Внутри:\r\n' +
      '  data/asher.db     — вся база: изделия, продажи, клиенты, долги, журнал\r\n' +
      '  data/images/      — фотографии изделий и сканы сертификатов\r\n\r\n' +
      'Как восстановить:\r\n' +
      '  1. Закройте систему (на сервере: systemctl stop asher).\r\n' +
      '  2. Удалите папку data целиком — вместе с файлами asher.db-wal\r\n' +
      '     и asher.db-shm, если они есть. Если оставить их рядом со старой\r\n' +
      '     базой, система возьмёт данные из них, а не из копии.\r\n' +
      '  3. Распакуйте этот архив в папку с системой — папка data появится заново.\r\n' +
      '  4. Запустите систему обратно.\r\n', 'utf8'),
  });

  const name = 'asher-' + new Date().toISOString().slice(0, 10) + '.zip';
  audit(userId, 'backup', 'settings', null,
    `Скачана резервная копия (${name}, файлов: ${entries.length}, ${откуда})`);
  /*
   * Отдаём потоком, а не собираем в памяти. Замер на 330 МБ фотографий:
   * прежняя сборка занимала в пике 733 МБ, вдвое больше самого архива,
   * и на сервере с гигабайтом памяти копия однажды просто перестала бы
   * скачиваться. Заодно магазин больше не замирает: раньше продавец ждал
   * ответа пять секунд на обычном экране, пока владелец качал копию.
   */
  await streamZip(entries, res, { filename: name });
}

module.exports = { создатьКлюч, убратьКлюч, ключЕсть, ключВерен, отдатьКопию, ДЛИНА };
