'use strict';
/*
 * Металл и проба: что подставлять в новое изделие и как не плодить опечатки.
 *
 * Магазин торгует белым золотом 750-й пробы. Раньше в форме «Белое золото»
 * и «750» были лишь серыми подсказками: поле выглядело заполненным, а на деле
 * оставалось пустым. Итог на Главной — одно и то же золото тремя строками:
 * «Белое золото 750», «Без металла» и «Белое золоти 750». Теперь:
 *   — металл и проба по умолчанию стоят в новом изделии и в строках приёмки
 *     настоящими значениями (их меняют в «Настройках»);
 *   — написание, отличающееся от привычного на одну букву, исправляется при
 *     сохранении: «Белое золоти» → «Белое золото», «желтое золото» →
 *     «Жёлтое золото»;
 *   — то, что уже заведено без металла или с опечаткой, владелец исправляет
 *     одной кнопкой на Главной (см. исправление()).
 *
 * Модуль не трогает базу при подключении: правила проверяются отдельно,
 * без сервера (тесты/металл-test.js).
 */

const МЕТАЛЛЫ = ['Белое золото', 'Жёлтое золото', 'Красное золото', 'Розовое золото',
  'Серебро', 'Платина', 'Палладий'];

// Пока владелец ничего не менял в настройках — белое золото 750-й пробы.
const ПО_УМОЛЧАНИЮ = { default_metal: 'Белое золото', default_fineness: '750' };

const сложить = s => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
const чисто = s => String(s || '').replace(/\s+/g, ' ').trim();

/*
 * Сколько правок отделяет одно написание от другого: вставка, удаление,
 * замена буквы или перестановка двух соседних («золтоо»). Больше двух нам
 * не интересно — считаем до первого превышения.
 */
function расстояние(a, b) {
  if (Math.abs(a.length - b.length) > 2) return 3;
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      const цена = a[i - 1] === b[j - 1] ? 0 : 1;
      d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + цена);
      if (i > 1 && j > 1 && a[i - 1] === b[j - 2] && a[i - 2] === b[j - 1]) {
        d[i][j] = Math.min(d[i][j], d[i - 2][j - 2] + 1);
      }
    }
  }
  return d[a.length][b.length];
}

/*
 * Привычное написание металла. Совпало без учёта регистра и «ё» — берём
 * образец как есть. Отличается ровно на одну правку от единственного образца —
 * это опечатка, исправляем. Всё остальное («Золото», «Белое золото 585»,
 * «Серебро с позолотой») оставляем как написано: угадывать мы не будем.
 * ещё — дополнительные образцы, например металл по умолчанию из настроек.
 */
function правильноеНаписание(металл, ещё = []) {
  const м = чисто(металл);
  if (!м) return '';
  const с = сложить(м);
  const образцы = [...ещё.map(чисто).filter(Boolean), ...МЕТАЛЛЫ];
  let лучший = null, лучшее = Infinity, ничья = false;
  for (const о of образцы) {
    const d = расстояние(с, сложить(о));
    if (d < лучшее) { лучший = о; лучшее = d; ничья = false; }
    else if (d === лучшее && сложить(о) !== сложить(лучший)) ничья = true;
  }
  if (лучшее === 0) return лучший;
  if (лучшее === 1 && !ничья && с.length >= 5) return лучший;
  return м;
}

// «750 пробы», «750-я проба», «750 пр.» — это всё «750».
function праваяПроба(проба) {
  const п = чисто(проба);
  const m = /^(\d{3,4})\s*(-?\s*(я|й|ой|ая))?\s*(пр(об[аыи]?)?)?\.?$/i.exec(п);
  return (m ? m[1] : п).slice(0, 10);
}

// Металл и проба по умолчанию из настроек. Пустое значение — «не подставлять».
function поУмолчанию() {
  const { getSetting } = require('./db');
  return {
    metal: getSetting('default_metal', ПО_УМОЛЧАНИЮ.default_metal),
    fineness: getSetting('default_fineness', ПО_УМОЛЧАНИЮ.default_fineness),
  };
}

/*
 * Во что превратится группа изделий по кнопке «исправить» на Главной, или
 * null, если исправлять нечего.
 *   — без металла → металл по умолчанию (и проба по умолчанию, если пробы нет);
 *   — опечатка в металле → привычное написание, проба та же;
 *   — металл по умолчанию без пробы → проба по умолчанию.
 * Пробу к чужому металлу не придумываем: жёлтое золото без пробы остаётся
 * без пробы.
 */
function исправление(металл, проба, умолч) {
  const м = чисто(металл), п = чисто(проба);
  const станетМ = м ? правильноеНаписание(м, [умолч.metal]) : правильноеНаписание(умолч.metal);
  if (!станетМ) return null;
  const своя = сложить(станетМ) === сложить(умолч.metal);
  const станетП = п ? праваяПроба(п) : (своя ? праваяПроба(умолч.fineness) : '');
  if (станетМ === м && станетП === п) return null;
  return { metal: станетМ, fineness: станетП };
}

module.exports = { МЕТАЛЛЫ, ПО_УМОЛЧАНИЮ, правильноеНаписание, праваяПроба, поУмолчанию, исправление };
